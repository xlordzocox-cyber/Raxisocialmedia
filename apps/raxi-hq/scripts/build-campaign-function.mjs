import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const target = '../../supabase/functions/_shared/campaign-domain.js';
const result = await build({ entryPoints: ['src/persistence/campaignCommands.ts'], bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2022' });
const source = '// GENERATED by npm run build:campaign-function. Do not edit.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Stale server domain bundle. Run npm run build:campaign-function.');
} else await writeFile(target, source);
