import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const target = '../../supabase/functions/_shared/supervised-campaign-domain.js';
const result = await build({
  entryPoints: ['../../server/agent-runtime/supervisedCampaignEdge.ts'],
  bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2022',
});
const source = '// GENERATED by npm run build:supervised-function. Do not edit.\n' + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== source.replaceAll('\r\n', '\n')) {
    throw new Error('Stale supervised Edge bundle. Run npm run build:supervised-function.');
  }
} else await writeFile(target, source);
